// Hand-drawn top levels of the blueprint. Every edge carries code references: literal
// `path@line@token` strings, or `ev('A1')`, the evidence an extraction agent found for claim A1
// (refs/*.json). The build checks each reference, and check.mjs lists the ones that moved or broke.
import { readFileSync, readdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const evidence = {}
for (const f of readdirSync(join(HERE, 'refs')).filter((n) => n.endsWith('.json'))) {
  for (const e of JSON.parse(readFileSync(join(HERE, 'refs', f), 'utf8'))) evidence[e.id] = e
}
// The references for a claim, only when the agent found it supported (and a human read it).
export function ev(...ids) {
  const out = []
  for (const id of ids) {
    const e = evidence[id]
    if (e && e.supported && Array.isArray(e.refs)) out.push(...e.refs)
  }
  return out
}

