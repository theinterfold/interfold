use crate::configuration::{OperationParams, HEADER};
use anyhow::{bail, Context, Result};
use e3_committee::{CiphernodesCommitteeSize, CommitteeMetadata};
use e3_fhe_params::{BfvPreset, BFV_ENCRYPTION_SCHEME, INTERFOLD_BFV_VERSION};
use e3_zk_config::metadata::CircuitDimensions;
use e3_zk_config::output_layout::DecryptionAggregatorLayout;
use std::{
    fs,
    path::{Path, PathBuf},
};

const GENERATED: &str = "// Generated by `pnpm generate:crypto-bindings`. Do not edit.\n";
pub const SOLIDITY_PATH: &str = "packages/interfold-contracts/contracts/lib/BfvProtocol.sol";
pub const NOIR_PATH: &str = "circuits/lib/src/configs/protocol.nr";

pub fn solidity(params: &OperationParams) -> Result<String> {
    let mut text = format!("{HEADER}pragma solidity >=0.8.27;\n\n{GENERATED}library BfvProtocol {{\n    bytes32 internal constant ENCRYPTION_SCHEME_ID = keccak256(\"{BFV_ENCRYPTION_SCHEME}\");\n    bytes32 internal constant CIRCUIT_VERSION = keccak256(\"{INTERFOLD_BFV_VERSION}\");\n");
    for (param_set, preset) in BfvPreset::ON_CHAIN_PARAMETER_SETS {
        let label = solidity_label(preset)?;
        let material = params.get(preset);
        text.push_str(&format!("\n    bytes32 internal constant {label}_CONFIG_ID =\n        {:#x};\n    uint8 internal constant {label}_PARAM_SET = {param_set};\n    bytes32 internal constant {label}_PARAM_SET_HASH =\n        {:#x};\n", material.config_id, material.parameter_hash));
    }
    for committee in CiphernodesCommitteeSize::ALL {
        let record = CommitteeMetadata::from(committee);
        let label = record.name.to_uppercase();
        text.push_str(&format!("\n    uint8 internal constant {label}_COMMITTEE_SIZE = {};\n    uint32 internal constant {label}_T = {};\n    uint32 internal constant {label}_H = {};\n    uint32 internal constant {label}_N = {};\n", record.committee_size, record.t, record.h, record.n));
    }
    let dimensions = CircuitDimensions::current();
    text.push_str(&format!("\n    uint256 internal constant MESSAGE_COEFFS_COUNT = {};\n    uint256 internal constant MESSAGE_COEFF_BYTE_LEN = {};\n    uint256 internal constant FIELD_BYTE_LEN = {};\n    uint256 internal constant PLAINTEXT_BYTE_LEN = {};\n", dimensions.message_coeffs_count, dimensions.message_coeff_byte_len, dimensions.field_byte_len, dimensions.plaintext_byte_len));
    let layout = DecryptionAggregatorLayout::current();
    text.push_str(&format!("\n    uint256 internal constant DEC_PUBLIC_INPUT_COUNT = {};\n    uint256 internal constant DEC_RETURN_PREFIX_LEN = {};\n    uint256 internal constant DEC_RETURN_COLUMN_COUNT = {};\n", layout.public_inputs.len(), layout.return_prefix.len(), layout.columns.len()));
    for (index, field) in layout.public_inputs.iter().enumerate() {
        text.push_str(&format!(
            "    uint256 internal constant DEC_{}_IDX = {index};\n",
            field.name.to_uppercase()
        ));
    }
    text.push_str("}\n");
    Ok(text)
}

/// Solidity name of an on-chain parameter set. `SECURE` keeps its deployed name for secure-8192.
fn solidity_label(preset: BfvPreset) -> Result<&'static str> {
    Ok(match preset {
        BfvPreset::InsecureThreshold64 => "INSECURE",
        BfvPreset::SecureThreshold8192 => "SECURE",
        BfvPreset::SecureThreshold16384 => "SECURE_16384",
        BfvPreset::InsecureThresholdLbfv => "INSECURE_LBFV",
        other => bail!("{other:?} has no on-chain parameter set"),
    })
}

pub fn noir_sources(root: &Path) -> Vec<(PathBuf, String)> {
    let dimensions = CircuitDimensions::current();
    let protocol = format!("{HEADER}\n{GENERATED}\npub global MAX_MSG_NON_ZERO_COEFFS: u32 = {};\npub global MESSAGE_COEFF_BYTE_LEN: u32 = {};\npub global FIELD_BYTE_LEN: u32 = {};\npub global PLAINTEXT_BYTE_LEN: u32 = {};\n", dimensions.message_coeffs_count, dimensions.message_coeff_byte_len, dimensions.field_byte_len, dimensions.plaintext_byte_len);
    let mut sources = vec![(root.join(NOIR_PATH), protocol)];
    // One parity matrix per artifact preset plus the shared smudging widths; see `parity_files`.
    let mut modules: String = crate::ARTIFACT_PRESETS
        .iter()
        .map(|preset| format!("pub mod parity_{};\n", crate::tier(*preset)))
        .collect();
    modules.push_str("pub mod smudging;\n");
    for committee in CiphernodesCommitteeSize::ALL {
        let values = committee.values();
        sources.push((
            root.join(format!("circuits/lib/src/configs/committee/{committee}/mod.nr")),
            format!("{HEADER}\n{GENERATED}\npub global N_PARTIES: u32 = {};\npub global T: u32 = {};\npub global H: u32 = {};\n\n{modules}", values.n, values.threshold, values.h),
        ));
    }
    sources
}

pub fn sync(root: &Path, check: bool) -> Result<()> {
    let params = OperationParams::both()?;
    let mut sources = noir_sources(root);
    sources.push((root.join(SOLIDITY_PATH), solidity(&params)?));
    // Validate every destination before publishing any file. Check mode never repairs outputs.
    let mut changes = Vec::new();
    for (path, expected) in sources {
        let current = match fs::read_to_string(&path) {
            Ok(current) => Some(current),
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => None,
            Err(error) => return Err(error).with_context(|| format!("Read {}", path.display())),
        };
        if current.as_deref() == Some(expected.as_str()) {
            continue;
        }
        if check {
            bail!(
                "{} is missing or stale; run pnpm generate:crypto-bindings",
                path.display()
            );
        }
        changes.push((path, expected));
    }
    crate::configuration::publish_changes(changes)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bindings_are_deterministic_and_checks_never_repair_missing_or_stale_files() {
        let temp = tempfile::tempdir().unwrap();
        let root = temp.path();
        assert!(sync(root, true).is_err());
        assert_eq!(fs::read_dir(root).unwrap().count(), 0);
        sync(root, false).unwrap();
        for name in ["ActiveCryptoConfig.sol", "BfvDecryptionLayout.sol"] {
            fs::write(
                root.join("packages/interfold-contracts/contracts/lib")
                    .join(name),
                "// Independently maintained Solidity.\n",
            )
            .unwrap();
        }
        let before = crate::tests::snapshot(root);
        sync(root, false).unwrap();
        sync(root, true).unwrap();
        assert_eq!(crate::tests::snapshot(root), before);
        let mut paths: Vec<_> = noir_sources(root)
            .into_iter()
            .map(|(path, _)| path)
            .collect();
        paths.push(root.join(SOLIDITY_PATH));
        for path in paths {
            let expected = fs::read(&path).unwrap();
            fs::remove_file(&path).unwrap();
            let before = crate::tests::snapshot(root);
            assert!(sync(root, true)
                .unwrap_err()
                .to_string()
                .contains(path.to_str().unwrap()));
            assert_eq!(crate::tests::snapshot(root), before);
            fs::write(&path, "stale").unwrap();
            let before = crate::tests::snapshot(root);
            let error = sync(root, true).unwrap_err().to_string();
            assert!(error.contains(path.to_str().unwrap()), "{error}");
            assert_eq!(crate::tests::snapshot(root), before);
            fs::write(&path, expected).unwrap();
        }
    }
}
