//! Emits SIZING-ONLY bin packages for the committee-side CKKS proof
//! circuits at a chosen ring degree `N` and fixed limb count `L`
//! (`ckks_preset_scaling`), each with a real witness from the production
//! builder, so `scripts/ckks-prove-package.sh` can measure how
//! constraints / compile RAM / prove time grow with `N`.
//!
//! Run (from the repo root):
//!   cargo run --release -p e3-zk-helpers --example gen_ckks_scale_provers -- \
//!     --n 1024 [--l 3] [--special 1] [--circuits c1,c2a,c2b,c6,c7,c8]
//!
//! Writes `circuits/bin/ckks_scaling/<pkg>_scale_n<N>/{Nargo.toml,Prover.toml,src/main.nr,src/configs.nr}`
//! and refreshes the `circuits/bin/ckks_scaling/Nargo.toml` workspace
//! member list. Nothing here is consumed by the node; the packages are
//! measurement fixtures for `docs/THRESHOLD_CKKS_PROVEN_PIPELINE_AT_SECURE_N.md`.

