// Writes `circuits/lib/src/vectors.nr` from `sdk/test-vectors/layout.json`: the plaintext slots of
// the seller and the buyer for fixed (seller step, seller share, buyer step, buyer share). The Noir
// tests of the offer circuits compare the encoding of the circuit with them.
//
//   node circuits/tools/vectors.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const { cases } = JSON.parse(readFileSync(join(root, 'sdk', 'test-vectors', 'layout.json'), 'utf8'))

const row = (slots) => `[${slots.join(', ')}]`
const party = (name, key) =>
  [`pub global ${name}_SLOTS: [[[Field; 128]; 3]; CASES] = [`, ...cases.map((c) => `    [${c[key].map(row).join(', ')}],`), '];'].join('\n')
const list = (name, type, values) => `pub global ${name}: [${type}; CASES] = [${values.join(', ')}];`

const output = [
  '// SPDX-License-Identifier: LGPL-3.0-only',
  '//',
  '// This file is provided WITHOUT ANY WARRANTY;',
  '// without even the implied warranty of MERCHANTABILITY',
  '// or FITNESS FOR A PARTICULAR PURPOSE.',
  '',
  '// Test vectors of the offer encoding.',
  '// GENERATED by examples/negotiation/circuits/tools/vectors.mjs from sdk/test-vectors/layout.json. Do not edit it.',
  '// Regenerate it from examples/negotiation with:',
  '//   node circuits/tools/vectors.mjs',
  '',
  `pub global CASES: u32 = ${cases.length};`,
  list(
    'SELLER_STEP',
    'Field',
    cases.map((c) => c.sellerStep),
  ),
  list(
    'SELLER_SHARE',
    'Field',
    cases.map((c) => c.sellerShare),
  ),
  list(
    'BUYER_STEP',
    'Field',
    cases.map((c) => c.buyerStep),
  ),
  list(
    'BUYER_SHARE',
    'Field',
    cases.map((c) => c.buyerShare),
  ),
  '/// `SELLER_SLOTS[case][ciphertext][slot]`: the three plaintexts of the seller (lanes 0..8, lanes 8..16, mask).',
  party('SELLER', 'seller'),
  '/// The same for the buyer.',
  party('BUYER', 'buyer'),
  '',
].join('\n')
writeFileSync(join(root, 'circuits', 'lib', 'src', 'vectors.nr'), output)
console.log(`wrote ${cases.length} cases`)
