    /// The leaf of a bid ciphertext with the given parts.
    fn leaf_of(
        hash: [u8; 32],
        commitment: Option<&[u8; 32]>,
        metadata: &[u8],
        recomputed: Option<[u8; 32]>,
    ) -> Result<String, ComputeError> {
        (policy().leaf)(&PublishedInput {
            index: 1,
            ciphertext: b"unused",
            ciphertext_hash: hash,
            commitment,
            metadata,
            recomputed,
        })
    }

    /// `bidder || uint40(index)`, as the contract publishes it.
    fn metadata_of(bidder: u8, index: u64) -> Vec<u8> {
        [vec![bidder; 20], index.to_be_bytes()[3..].to_vec()].concat()
    }

