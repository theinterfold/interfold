//! The FHE program of the token-launch example: a sealed, one-batch, uniform-price token sale with
//! private budgets and private max prices.
//!
//! A sale is two E3s that run this program: round 1 and round 2. Each bid is one plaintext,
//! encrypted once under each key. The program only adds: the committee never learns a bid, and it
//! reveals the budget sums of a few price levels, not the demand curve.
//!
//! Input 0 of a round is its configuration, [`Config`]: not a ciphertext. `TokenLaunchProgram`
//! inserts its leaf (round 2 replaces it once round 1 has decrypted), so the compute proof binds the
//! config, and with it the probed levels, through the input root.
//!
//! The SIMD plaintext of a bid has 128 slots, see [`layout`]:
//!
//! ```text
//! slot l * LANES + j       d_j(B) if l <= b else 0    (the base 4 digit j of the budget B)
//! slot FLAG_BASE + i / 8   2^(i % 8)                  (i the bid index)
//! every other slot         0
//! ```
//!
//! The bid proof binds `b`, `B` and `i` into the plaintext, and the contract binds `i` into the leaf
//! metadata, so the program needs no metadata of its own beyond the bidder and the index.
//!
//! The processor receives the config and every bid whose bytes open its commitment, adds the bids,
//! and multiplies the sum by the keep mask of the config: the cells of the probed levels and all the
//! flag cells stay, every other slot is 0. After decryption, for a kept level `l`,
//! `cell(l, j)` is the sum of `d_j(B_i)` over the counted bids with `b_i >= l`, so the budget sum of
//! those bids is `sum_j 4^j cell(l, j)`; and the flag cells hold the counted bitmap. Every slot is at
//! most `MAX_BIDDERS * 3 = 255`, below the plaintext modulus `t = 257`, so no slot wraps. The
//! decryption is verified on chain, so the counted set needs no extra trust. The program needs no key.
//!
//! The slot layout lives in [`layout`] only. `TokenLaunchProgram` (Solidity) and `sdk/src/layout.ts`
//! decode the same layout, and `sdk/test-vectors/layout.json`, generated by the tests of this crate,
//! pins them.

