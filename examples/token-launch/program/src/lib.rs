    #[test]
    fn the_secure_process_runs_the_policy_and_the_round_over_the_selected_bids() -> Result<()> {
        // Bid 1 carries the commitment of the bytes of bid 0, so its own bytes do not open it: it
        // is dropped and its flag is not counted. Bids 0 and 2 count, and the mask keeps level 6.
        use e3_bfv_client::client::compute_ct_commitment_with_params;
        use e3_compute_provider::{Batching, ComputeInput, FHEInputs, PublishedData};
        let fixture = fixture()?;
        let bids: [Bid; 3] = [(3, 100, 0), (9, 500, 1), (6, 40, 2)];
        let cts = bids
            .iter()
            .map(|&(b, budget, i)| encrypt(&fixture, &bid_slots(SLOTS, b, budget, i)))
            .collect::<Result<Vec<_>>>()?;
        let open = |bytes: &[u8]| compute_ct_commitment_with_params(bytes, &fixture.params);
        let commitments = [open(&cts[0])?, open(&cts[0])?, open(&cts[2])?];
        let mut published = vec![PublishedData {
            commitment: Some([0; 32]),
            metadata: vec![],
        }];
        for (i, commitment) in commitments.into_iter().enumerate() {
            published.push(PublishedData {
                commitment: Some(commitment),
                metadata: metadata_of(i as u8 + 1, i as u64),
            });
        }
        let ciphertexts: Vec<(Vec<u8>, u64)> = std::iter::once(config(1, 1 << 6).encode())
            .chain(cts.iter().cloned())
            .enumerate()
            .map(|(i, bytes)| (bytes, i as u64))
            .collect();
        let input = ComputeInput {
            fhe_inputs: FHEInputs {
                ciphertexts,
                params: e3_fhe_params::encode_bfv_params(&fixture.params),
                committee_key: vec![],
            },
            published,
        };
        let (_, output, selected) = input
            .run_selected(fhe_processor, policy(), Batching::Sequential)
            .map_err(|e| anyhow::anyhow!("{e}"))?;
        assert_eq!(selected, [0, 1, 3]);
        let slots = decrypt(&fixture, &output)?;
        assert_eq!(slots, expected_slots(&[bids[0], bids[2]], 1 << 6));
        let output = decode_output(&slots).unwrap();
        assert_eq!(output.counted_bitmap(), 1 | 1 << 2);
        assert_eq!(output.level_sum(6), 40);
        assert_eq!(output.level_sum(3), 0, "level 3 is not probed");
        Ok(())
    }

