    fn array<V: std::fmt::Display>(values: &[V]) -> String {
        let items: Vec<String> = values.iter().map(V::to_string).collect();
        format!("[{}]", items.join(","))
    }

    /// The published plaintext of `slots`: 128 little-endian `u64` coefficients, as `0x` hex. The
    /// fixture has to encrypt and decrypt, because a fresh plaintext only decodes as SIMD.
    /// `e3_bfv_client::client::simd_decode` (what the SDK calls) must invert it.
    fn plaintext_hex(fixture: &Fixture, slots: &[u64]) -> Result<String> {
        let ciphertext = Ciphertext::from_bytes(&encrypt(fixture, slots)?, &fixture.params)?;
        let decrypted = fixture.secret_key.try_decrypt(&ciphertext)?;
        let coefficients = Vec::<u64>::try_decode(&decrypted, Encoding::poly())?;
        assert_eq!(
            e3_bfv_client::client::simd_decode(&coefficients, PRESET)?,
            slots
        );
        let mut out = String::from("0x");
        for coefficient in coefficients {
            write!(out, "{}", hex::encode(coefficient.to_le_bytes()))?;
        }
        Ok(out)
    }

